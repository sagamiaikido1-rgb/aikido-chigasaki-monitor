import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from datetime import date
import analyze as an

# 2026-11-03 0時半に実際の画面で読んだ数(1月分)
def cell(d, st, en, txt):
    return f"<td onclick=\"changeCheckStatus('x','2027/1/{d}',1,'{st}{en}')\">{txt}</td>"
judo = "<table><tr>" + "".join([
    cell(6, "1800", "2100", "抽選(9)"), cell(10, "0900", "1200", "×"), cell(10, "1800", "2100", "抽選(1)"),
    cell(13, "1800", "2100", "抽選(9)"), cell(17, "0900", "1200", "抽選(9)"), cell(17, "1800", "2100", "抽選(0)"),
    cell(20, "1800", "2100", "抽選(9)"), cell(24, "0900", "1200", "×"), cell(24, "1800", "2100", "抽選(1)"),
    cell(27, "1800", "2100", "抽選(9)"), cell(31, "0900", "1200", "抽選(9)")]) + "</tr><tr><td>1/3(日)</td><td>休館</td></tr></table>"
kendo = "<table><tr>" + cell(17, "0900", "1200", "抽選(11)") + cell(31, "0900", "1200", "抽選(10)") + cell(10, "0900", "1200", "×") + "</tr></table>"
cells = {"柔道": an.parse_cells(judo), "柔剣": an.parse_cells(kendo)}
cur = {}
def put(k, ids):
    cur[k] = list(ids)
for d in (6, 20):
    put(f"2027-01-{d:02d} 1800-2100", [1, 2, 3, 4, 5, 6, 7, 8, 10])
for d in (13, 27):
    put(f"2027-01-{d:02d} 1800-2100", [9, 10, 11, 12, 13, 14, 15, 16, 18])
put("2027-01-17 0900-1200", [12, 14, 16, 18]); put("2027-01-17 0900-1200 柔剣", [1, 2, 3, 4, 5])
put("2027-01-31 0900-1200", [12, 14, 16, 18]); put("2027-01-31 0900-1200 柔剣", [6, 7, 8, 9, 11])
put("2027-01-10 1800-2100", [17]); put("2027-01-24 1800-2100", [17])
g = {x["g"]: x for x in an.build(2027, 1, cells, {date(2027, 1, 3)}, cur)}
assert set(g) == {"2027-01-06 1800-2100", "2027-01-10 1800-2100", "2027-01-13 1800-2100", "2027-01-17 0900-1200",
                  "2027-01-20 1800-2100", "2027-01-24 1800-2100", "2027-01-27 1800-2100", "2027-01-31 0900-1200"}, sorted(g)
x = g["2027-01-17 0900-1200"]
assert x["ours"] == 9 and x["others"] == 2 and abs(x["rate"] - 9 / 11) < 1e-3, x
assert g["2027-01-31 0900-1200"]["others"] == 1 and g["2027-01-06 1800-2100"]["rate"] == 1.0
assert g["2027-01-10 1800-2100"]["kind"] == "日曜夜" and g["2027-01-10 1800-2100"]["others"] == 0
assert "2027-01-17 1800-2100" not in g   # 連盟の申込がない日曜夜は載せない
r = {"year": 2027, "month": 1, "day": 31, "start": "0900", "end": "1200", "text": "市体育館 柔剣道場"}
assert an.row_slot(r, 2027, 1) is None and "市体育館" in an.other_label(r)
print("analyze ok")
